import {readFile,readdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {releasePolicy} from './release-policy.mjs';
import {fileURLToPath} from 'node:url';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
export async function catanManifest({check=false}={}) {
 const root=new URL('../',import.meta.url),rules=await readdir(new URL('play/catan/rules/',root));
 const paths=['play/catan/entropy.js','play/catan/module.js','play/relay/replica.js','play/relay/protocol.js',...rules.filter(f=>f.endsWith('.js')).map(f=>'play/catan/rules/'+f)].sort();
 const files=[];for(const path of paths)files.push({path,sha256:hash(await readFile(new URL(path,root)))});
 const releaseFile=new URL('../release.json',import.meta.url),stored=JSON.parse(await readFile(releaseFile,'utf8')),policy=releasePolicy(stored);
 if(JSON.stringify(stored)!==JSON.stringify(policy)){if(check)throw Error('Release policy needs generation. Run node scripts/catan-manifest.mjs.');await writeFile(releaseFile,JSON.stringify(policy,null,2)+'\n');}
 const manifest={schemaVersion:1,rulesVersion:'2.1.0',releaseVersion:policy.version,breaking:policy.breaking,compatibilityId:policy.compatibilityId,files,digest:hash(JSON.stringify(files))};
 const output='// Generated by scripts/catan-manifest.mjs; do not edit.\nexport const CATAN_ARTIFACT = Object.freeze('+JSON.stringify(manifest,null,2)+');\n';
 const target=new URL('play/catan/artifact.js',root);
 if(check){if(await readFile(target,'utf8')!==output)throw Error('Catan artifact is stale. Run node scripts/catan-manifest.mjs.');}
 else await writeFile(target,output);
 return manifest;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){const value=await catanManifest({check:process.argv.includes('--check')});console.log('Catan artifact',value.digest);}
